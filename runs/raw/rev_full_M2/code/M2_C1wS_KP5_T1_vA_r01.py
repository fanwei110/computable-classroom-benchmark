import numpy as np
from scipy.stats import norm

# =========================
# 输入参数
# =========================
position_value = 1_850_000      # 头寸价值（人民币元）
annual_vol = 0.218              # 年化波动率
trading_days = 252              # 一年中的交易天数（行业惯例）

# =========================
# 波动率换算
# =========================
daily_vol = annual_vol / np.sqrt(trading_days)   # 日波动率

# =========================
# 正态分布分位数（左尾）
# =========================
z_95 = norm.ppf(0.05)   # 95%置信水平对应的分位数（负值）
z_99 = norm.ppf(0.01)   # 99%置信水平对应的分位数（负值）

# =========================
# 计算一日期限的 VaR（绝对值，以损失为正）
# =========================
var_95_1d = abs(z_95) * daily_vol * position_value

# =========================
# 缩放至十日期限：VaR 随 sqrt(时间) 缩放（假设零均值、独立同分布）
# =========================
horizon_10d = np.sqrt(10)
var_99_10d = abs(z_99) * daily_vol * position_value * horizon_10d

# =========================
# 整理输出
# =========================
result = {
    'var_95_1d': round(var_95_1d, 2),   # 保留两位小数（人民币）
    'var_99_10d': round(var_99_10d, 2)
}

# 如需课堂投屏展示，可直接打印
print(result)
