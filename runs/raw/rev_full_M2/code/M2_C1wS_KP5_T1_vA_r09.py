import numpy as np
from scipy.stats import norm

# =========================
# 输入参数
# =========================
position_value = 1_850_000          # 头寸市值（人民币元）
annual_vol = 0.218                  # 年化波动率
trading_days = 252                  # 假设一年 252 个交易日

# =========================
# 1. 年化波动率换算为一日波动率
# =========================
daily_vol = annual_vol / np.sqrt(trading_days)

# =========================
# 2. 置信水平对应的正态分位数（左尾）
#    注意：VaR 关注左尾损失，分位数为负值，
#    但 VaR 习惯报告为正数，因此取绝对值。
# =========================
z_95 = norm.ppf(0.05)   # 95% 置信水平对应 5% 左尾分位
z_99 = norm.ppf(0.01)   # 99% 置信水平对应 1% 左尾分位

# =========================
# 3. 计算 VaR
#    VaR = 头寸价值 × 波动率 × 分位数绝对值
#    一日 VaR 直接用日波动率；
#    十日 VaR 用 sqrt(10) 对日波动率进行缩放。
# =========================
var_95_1d = position_value * daily_vol * (-z_95)   # 已取正数
var_99_1d = position_value * daily_vol * (-z_99)   # 日基础用于十日缩放
var_99_10d = position_value * (daily_vol * np.sqrt(10)) * (-z_99)  # 十日 VaR

# =========================
# 4. 填入结果字典
# =========================
result = {
    'var_95_1d': round(var_95_1d, 2),    # 人民币元，保留两位小数
    'var_99_10d': round(var_99_10d, 2)
}

# =========================
# 输出结果（方便查看）
# =========================
if __name__ == "__main__":
    print("=== 参数法 VaR 计算结果 ===")
    print(f"95% 置信水平一日 VaR : {result['var_95_1d']:,.2f} 元")
    print(f"99% 置信水平十日 VaR : {result['var_99_10d']:,.2f} 元")
