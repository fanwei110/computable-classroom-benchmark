import numpy as np
from scipy.stats import norm

# ==========================================
# 输入参数
# ==========================================
position = 1_850_000  # 头寸：185万元，以人民币计
annual_vol = 0.218    # 年化波动率：21.8%
trading_days = 252    # 假设：一年按252个交易日计算（金融界标准惯例）

# ==========================================
# 步骤1：将年化波动率换算到一日期限
# ==========================================
# 根据平方根法则：sigma_daily = sigma_annual / sqrt(T)
daily_vol = annual_vol / np.sqrt(trading_days)

# ==========================================
# 步骤2：套用正态分位数计算一日VaR
# ==========================================
# 参数法（Delta-Normal）假设损益服从正态分布
z_95 = norm.ppf(0.95)  # 95%置信水平对应的正态分位数
z_99 = norm.ppf(0.99)  # 99%置信水平对应的正态分位数

# 95%置信水平的一日VaR (人民币)
var_95_1d = position * daily_vol * z_95

# ==========================================
# 步骤3：缩放到十日期限并计算99%置信水平的VaR
# ==========================================
# 根据平方根时间法则：VaR_T = VaR_1 * sqrt(T)
var_99_10d = var_95_1d * (z_99 / z_95) * np.sqrt(10)

# ==========================================
# 步骤4：填充 result 字典
# ==========================================
result = {
    'var_95_1d': var_95_1d,
    'var_99_10d': var_99_10d
}

# 打印结果以便课堂投屏展示
print(f"计算参数假设：")
print(f"- 年交易日数: {trading_days} 天")
print(f"- 日波动率: {daily_vol:.6f} ({daily_vol*100:.4f}%)")
print(f"- 正态分布分位数 Z(95%): {z_95:.4f}")
print(f"- 正态分布分位数 Z(99%): {z_99:.4f}")
print("-" * 40)
print(f"95%置信水平的一日VaR: ¥{result['var_95_1d']:,.2f}")
print(f"99%置信水平的十日VaR: ¥{result['var_99_10d']:,.2f}")

