import numpy as np
from scipy import stats

# ============================================================
# 输入参数
# ============================================================
portfolio_value = 1_850_000       # 头寸价值（元）
annual_volatility = 0.218         # 年化收益波动率 21.8%
trading_days_per_year = 252       # 一年交易日数（业界惯例）

# ============================================================
# 将年化波动率转换为日波动率
# ============================================================
daily_volatility = annual_volatility / np.sqrt(trading_days_per_year)

# ============================================================
# 计算 Z 分位数
# ============================================================
z_95 = stats.norm.ppf(0.95)       # 95% 置信水平对应的 Z 值
z_99 = stats.norm.ppf(0.99)       # 99% 置信水平对应的 Z 值

# ============================================================
# (i) 95% 一日 VaR（delta-normal 模型）
#     VaR = 头寸价值 × 日波动率 × Z_95
# ============================================================
var_95_1d = portfolio_value * daily_volatility * z_95

# ============================================================
# (ii) 99% 十日 VaR（delta-normal 模型）
#      十日波动率 = 日波动率 × sqrt(10)
#      VaR = 头寸价值 × 十日波动率 × Z_99
# ============================================================
volatility_10d = daily_volatility * np.sqrt(10)
var_99_10d = portfolio_value * volatility_10d * z_99

# ============================================================
# 结果输出
# ============================================================
result = {
    'var_95_1d': var_95_1d,
    'var_99_10d': var_99_10d
}

# 打印详细信息
print("=" * 55)
print("Delta-Normal VaR 计算结果")
print("=" * 55)
print(f"头寸价值:         {portfolio_value:>14,.2f} 元")
print(f"年化波动率:       {annual_volatility * 100:>14.1f} %")
print(f"日波动率:         {daily_volatility * 100:>14.4f} %")
print(f"十日波动率:       {volatility_10d * 100:>14.4f} %")
print("-" * 55)
print(f"Z(95%):           {z_95:>14.6f}")
print(f"Z(99%):           {z_99:>14.6f}")
print("-" * 55)
print(f"95% 一日 VaR:     {var_95_1d:>14,.2f} 元")
print(f"99% 十日 VaR:     {var_99_10d:>14,.2f} 元")
print("=" * 55)
