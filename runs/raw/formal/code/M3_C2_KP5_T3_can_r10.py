import numpy as np
from scipy.stats import norm

# ==========================================
# 已知参数
# ==========================================
position_value = 2_700_000  # 头寸金额（元）
sigma_annual = 0.24         # 年化波动率（24%）
confidence_level = 0.95     # 置信水平（95%）

# ==========================================
# 假设处理
# ==========================================
# 题目未指明日历日还是交易日，按照《证券投资学》及业界惯例，采用一年252个交易日进行时间平方根法则换算
trading_days_per_year = 252

# ==========================================
# 计算步骤
# ==========================================

# 第一步：将年化波动率换算到一日期限
# 根据时间平方根法则：sigma_1d = sigma_annual / sqrt(T)
sigma_1d = sigma_annual / np.sqrt(trading_days_per_year)

# 第二步：套用 95% 正态分位数
# 使用 Delta-Normal 参数法，获取标准正态分布的 95% 分位数
z_95 = norm.ppf(confidence_level)

# 第三步：计算 95% 一日 VaR
# VaR = 头寸金额 * 一日波动率 * 正态分位数
var_95_1d = position_value * sigma_1d * z_95

# ==========================================
# 输出契约
# ==========================================
result = {
    'var_95_1d': var_95_1d
}

# 控制台输出展示（便于课堂投屏讲解）
print(f"假设一年交易日: {trading_days_per_year} 天")
print(f"一日期限波动率: {sigma_1d:.6f}")
print(f"95% 正态分位数: {z_95:.6f}")
print(f"95% 一日 VaR金额: {var_95_1d:.2f} 元")
print(f"\n最终结果字典: {result}")
