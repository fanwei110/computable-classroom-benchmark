import numpy as np
from scipy.stats import norm

# ============================================================
# 参数
# ============================================================
annual_vol = 0.24          # 年化波动率
position   = 2_700_000    # 头寸金额（元）
confidence = 0.95          # 置信水平
trading_days = 252         # 一年交易日数（标准假设）

# ============================================================
# Step 1: 年化波动率 → 日期波动率
#   根据平方根时间法则：σ_daily = σ_annual / sqrt(T)
# ============================================================
daily_vol = annual_vol / np.sqrt(trading_days)

# ============================================================
# Step 2: 95% 正态分位数
#   VaR 是损失分位数，取右尾（上侧），即 norm.ppf(0.95)
# ============================================================
z_95 = norm.ppf(confidence)   # ≈ 1.6449

# ============================================================
# Step 3: 计算 95% 一日 VaR
#   VaR = z × σ_daily × Position
# ============================================================
var_95_1d = z_95 * daily_vol * position

# ============================================================
# 输出
# ============================================================
result = {
    'var_95_1d': var_95_1d
}

# 课堂展示
print(f"年化波动率:        {annual_vol:.2%}")
print(f"交易日数:          {trading_days}")
print(f"日期波动率:        {daily_vol:.6f} ({daily_vol:.2%})")
print(f"95% 正态分位数:    {z_95:.4f}")
print(f"头寸金额:          {position:,.0f} 元")
print(f"95% 一日 VaR:      {var_95_1d:,.2f} 元")
print(f"\nresult = {result}")
