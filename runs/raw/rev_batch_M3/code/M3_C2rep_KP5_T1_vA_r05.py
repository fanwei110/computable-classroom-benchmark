import numpy as np
from scipy.stats import norm

# ==========================================
# 已知参数
# ==========================================
position_value = 1_850_000      # 头寸价值（元）
annual_vol = 0.218              # 年化收益波动率

# ==========================================
# 假设处理
# ==========================================
# 假设一年有 252 个交易日，这是将年化波动率转换为日波动率的标准市场惯例
trading_days_per_year = 252

# ==========================================
# 1. 将年化波动率换算到一日期限
# ==========================================
# 根据波动率的时间缩放法则：sigma_daily = sigma_annual / sqrt(T)
daily_vol = annual_vol / np.sqrt(trading_days_per_year)

# ==========================================
# 2. 对两个置信水平套用正态分位数
# ==========================================
# Delta-normal 模型下，使用标准正态分布的逆累积分布函数（ppf）获取临界值
z_95 = norm.ppf(0.95)
z_99 = norm.ppf(0.99)

# ==========================================
# 3. 计算 VaR 并缩放到十日期限，以人民币报告
# ==========================================
# (i) 95% 一日 VaR
# VaR = 头寸价值 × 日波动率 × 正态分位数
var_95_1d = position_value * daily_vol * z_95

# (ii) 99% 十日 VaR
# 先将日波动率缩放至10日：sigma_10d = sigma_1d * sqrt(10)
vol_10d = daily_vol * np.sqrt(10)
var_99_10d = position_value * vol_10d * z_99

# ==========================================
# 4. 填充 result
# ==========================================
# 按照金融惯例，结果保留两位小数（精确到分）
result = {
    'var_95_1d': round(var_95_1d, 2),
    'var_99_10d': round(var_99_10d, 2)
}

# 投屏输出展示
print("--- 在险价值 计算 ---")
print(f"日波动率: {daily_vol:.6f}")
print(f"正态分位数(95%): {z_95:.6f}")
print(f"正态分位数(99%): {z_99:.6f}")
print(f"(i) 95% 一日 VaR: ¥{result['var_95_1d']:,.2f}")
print(f"(ii) 99% 十日 VaR: ¥{result['var_99_10d']:,.2f}")
