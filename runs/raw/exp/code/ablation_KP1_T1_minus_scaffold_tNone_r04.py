import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

# ------------------------------------------------------------
# 1. 输入数据
# ------------------------------------------------------------
# 年化波动率 (已用小数表示)
vol = np.array([0.187, 0.243, 0.312])

# 相关系数矩阵
corr_matrix = np.array([
    [1.0,   0.21, -0.13],
    [0.21,  1.0,   0.37],
    [-0.13, 0.37,  1.0]
])

# ------------------------------------------------------------
# 2. 构建协方差矩阵
# ------------------------------------------------------------
# 协方差矩阵 = diag(vol) * corr_matrix * diag(vol)
cov_matrix = np.diag(vol) @ corr_matrix @ np.diag(vol)

# ------------------------------------------------------------
# 3. 求解全局最小方差组合 (允许卖空, 满仓约束)
# ------------------------------------------------------------
# 问题: min w' Σ w   s.t. w'1 = 1
# 解析解: w_mvp = (Σ^{-1} * 1) / (1' Σ^{-1} 1)

n = len(vol)
ones = np.ones(n)

# 逆协方差矩阵
cov_inv = np.linalg.inv(cov_matrix)

# MVP权重
w_mvp = cov_inv @ ones / (ones @ cov_inv @ ones)

# MVP年化波动率
var_mvp = w_mvp @ cov_matrix @ w_mvp
vol_mvp = np.sqrt(var_mvp)  # 年化波动率 (已以小数表示)

# ------------------------------------------------------------
# 4. 输出验证 (可选, 不输出到最终结果)
# ------------------------------------------------------------
print("=== 全局最小方差组合 (MVP) ===")
print(f"权重 (w1, w2, w3): {w_mvp}")
print(f"年化波动率: {vol_mvp:.6f} ({vol_mvp*100:.4f}%)")

# ------------------------------------------------------------
# 5. 构建 result 字典
# ------------------------------------------------------------
result = {
    'mvp_weights': w_mvp,
    'mvp_vol_annual': vol_mvp
}

# 打印 result 以便课堂展示
print("\n=== result 字典 ===")
print(result)

