"""Assemble the FORMAL C1/C3 prompt sets from the LLM-simulated persona
phrasings (disclosed design - see DEVIATIONS.md #3).

Provenance: the improvised phrasings were generated by a fourth LLM (not
among the three evaluated models) role-playing two instructor personas,
from task essences containing no convention information. They are frozen
here, before any formal generation, under honest labeling - NOT presented
as human instructor submissions.

Per-task variant selection (mechanical, logged): for each persona, use V1
unless V1 trips the convention-leak screen, in which case use V2; if both
trip, keep V1 and disclose. The screen uses convention WORDS only (the
numeric-data slashes that appear in classroom phrasing would false-positive
the C2 pattern list).

Output:
  prompts/C1_source/persona_A.md, persona_B.md  (frozen source, honest header)
  prompts/C1_source/variant_selection.md        (selection log)
  prompts/C1_final/{task}_{A|B}.md = phrasing + zh output contract
  prompts/C3_final/{task}_{A|B}.md = phrasing + zh convention header + contract
"""

import re
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
TASKS = HERE.parent / "tasks"
HEADER_ZH = (HERE / "convention_header_zh.txt").read_text(encoding="utf-8").strip()

SOURCE = {
    "A": HERE / "pilot_simulated" / "teacher_A_simulated.md",
    "B": HERE / "pilot_simulated" / "teacher_B_simulated.md",
}

PROVENANCE_HEADER = """# C1/C3 即兴措辞 — 人设 {persona}（LLM 模拟，正式冻结件）

> 来源披露：本文件中的全部措辞由一个未被本基准评测的大模型按教师人设模拟生成
> （人设 {persona}：{persona_desc}），生成时仅提供零约定的任务要素。
> 论文 §IV.C 与 DEVIATIONS.md #3 如实披露此来源；其生态效度在论文局限段讨论。
> 本文件自预注册仓库收录之时起冻结，正式实验仅使用 variant_selection.md
> 中记录的入选变体。

---
"""

PERSONA_DESC = {
    "A": "五十多岁资深教授，句子完整、参数报得齐整",
    "B": "三十出头年轻教师，碎片化短句、中英混杂",
}

# Convention-WORD screen for phrasings (no slash/number patterns - those
# false-positive on classroom data like "收益7.1%/12.4%").
PHRASING_FORBIDDEN = [
    r"\b252\b", r"\b250\b", r"\b365\b",
    r"交易日", r"日历日", r"自然日",
    r"复利", r"ddof", r"样本标准差", r"总体标准差",
    r"单尾", r"双尾", r"线性插值", r"布林森", r"Brinson",
    r"几何平均折算", r"小数表示", r"百分比表示",
]


def parse_phrasings(path):
    text = Path(path).read_text(encoding="utf-8")
    out = {}
    blocks = re.split(r"^### (KP\d_T\d)", text, flags=re.M)[1:]
    for task_id, body in zip(blocks[0::2], blocks[1::2]):
        v1 = re.search(r"^V1:\s*(.+?)(?=^V2:)", body, re.M | re.S)
        v2 = re.search(r"^V2:\s*(.+?)(?=^###|\Z)", body, re.M | re.S)
        out[task_id] = [m.group(1).strip() for m in (v1, v2) if m]
    if len(out) != 18:
        raise ValueError(f"{path}: expected 18 tasks, found {len(out)}")
    return out


def leaks(text):
    return [p for p in PHRASING_FORBIDDEN if re.search(p, text, re.I)]


def output_contract_zh(spec):
    keys = ", ".join(f"'{k}'" for k in spec["required_keys"])
    line = f"输出契约：把所有要求的输出存入名为 `result` 的字典，键名严格为：{keys}。"
    if spec["figure_required"]:
        line += " 将图保存为文件，并把文件路径存入 result['figure_path']。"
    return line


def main():
    (HERE / "C1_source").mkdir(exist_ok=True)
    (HERE / "C1_final").mkdir(exist_ok=True)
    (HERE / "C3_final").mkdir(exist_ok=True)

    selection_log = ["# C1/C3 入选变体记录（机械规则：V1 无泄漏则 V1，否则 V2）", ""]
    n = 0
    for persona, src in SOURCE.items():
        phr = parse_phrasings(src)
        # freeze the source verbatim under an honest provenance header
        body = re.split(r"^---\s*$", src.read_text(encoding="utf-8"),
                        maxsplit=1, flags=re.M)[1]
        (HERE / "C1_source" / f"persona_{persona}.md").write_text(
            PROVENANCE_HEADER.format(persona=persona,
                                     persona_desc=PERSONA_DESC[persona]) + body,
            encoding="utf-8")

        for task_id in sorted(phr):
            v1, v2 = phr[task_id]
            l1 = leaks(v1)
            if not l1:
                chosen, which = v1, "V1"
            else:
                l2 = leaks(v2)
                if not l2:
                    chosen, which = v2, "V2"
                    selection_log.append(
                        f"- {task_id} 人设{persona}: V1 含约定词 {l1} -> 改用 V2")
                else:
                    chosen, which = v1, "V1"
                    selection_log.append(
                        f"- {task_id} 人设{persona}: V1/V2 均含约定词 "
                        f"({l1}/{l2}) -> 保留 V1 并披露")
            spec = yaml.safe_load((TASKS / f"{task_id}.yaml").read_text(encoding="utf-8"))
            contract = output_contract_zh(spec)
            stem = f"{task_id}_{persona}.md"
            (HERE / "C1_final" / stem).write_text(
                f"{chosen}\n\n{contract}\n", encoding="utf-8")
            (HERE / "C3_final" / stem).write_text(
                f"{chosen}\n\n{HEADER_ZH}\n\n{contract}\n", encoding="utf-8")
            if which == "V1" and not l1:
                selection_log.append(f"- {task_id} 人设{persona}: V1（无泄漏）")
            n += 2

    (HERE / "C1_source" / "variant_selection.md").write_text(
        "\n".join(selection_log) + "\n", encoding="utf-8")
    print(f"assembled {n} formal prompts (C1_final + C3_final, 36 each); "
          f"selection log written")
    for line in selection_log:
        if "->" in line:
            print("  " + line)


if __name__ == "__main__":
    main()
